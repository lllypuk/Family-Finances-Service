#!/usr/bin/env bash
# Обновление сервиса на сервере: вход в реестр, подмена адреса образа в .env,
# перезапуск через compose.
#
# Запускается по ssh стадией deploy из .gitlab-ci.yml. Скрипт живёт в
# репозитории, а не heredoc'ом внутри YAML: так он проверяется shellcheck'ом и
# приезжает на сервер тем же tar, что и compose.
#
# Токен реестра приходит первой строкой stdin, а не аргументом: аргументы
# процесса видны в `ps` любому пользователю сервера всё время выката.
#
#   printf '%s\n' "$TOKEN" | bash release.sh <каталог> <реестр> <пользователь> <образ>

set -eu

dir=${1:?первым аргументом каталог развёртывания}
registry=${2:?вторым аргументом адрес реестра}
user=${3:?третьим аргументом пользователь реестра}
image=${4:?четвёртым аргументом образ с тегом}

read -r token

cd "$dir"

# .env остаётся на сервере и в CI не приезжает: в нём раскладка машины. Его
# отсутствие означает, что окружение вообще не разворачивали, и молча создавать
# его выкату нечем.
if ! grep -q '^FFS_IMAGE=' .env; then
	echo "в $dir/.env нет FFS_IMAGE — окружение не развёрнуто, см. deploy/README.md" >&2
	exit 1
fi

# Уборка ставится до входа в реестр, а не после: между login и trap любой отказ
# оставил бы учётные данные в ~/.docker/config.json. Переменная объявляется
# заранее — под `set -u` trap с неустановленной $tmp сам упал бы.
tmp=
trap 'rm -f "$tmp"; docker logout "$registry" >/dev/null 2>&1 || true' EXIT

printf '%s' "$token" | docker login --username "$user" --password-stdin "$registry"

# Копия базы снимается ДО подмены образа: новая версия применяет миграции на
# старте, и снимок, взятый после неё, откату уже не годится. Запускается
# одноразовым контейнером текущего образа — он на месте, раз сервис работал.
# Первый выкат базы ещё не имеет, снимать нечего.
if [ -f data/budget.db ]; then
	echo "снимаю копию базы перед выкатом"
	docker compose run --rm --no-deps -T app backup
fi

# Новая версия .env собирается рядом и заезжает на место одним mv: оборванная
# правка по месту оставила бы окружение с половиной строки. Права копируются с
# оригинала.
tmp=$(mktemp .env.XXXXXX)
cp -p .env "$tmp"

# Строка образа переписывается без sed намеренно: значение приходит снаружи, а в
# шаблоне замены часть символов значат не себя.
{ grep -v '^FFS_IMAGE=' .env || true; printf 'FFS_IMAGE=%s\n' "$image"; } >"$tmp"
mv "$tmp" .env

docker compose pull
# --wait: выкат падает, если сервисы не дошли до healthy, а не рапортует об
# успехе на контейнере в рестарте.
docker compose up -d --remove-orphans --wait
docker compose ps
